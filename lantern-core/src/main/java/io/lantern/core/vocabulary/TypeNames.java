package io.lantern.core.vocabulary;

import java.util.Collection;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;

/**
 * Generates a class with one constant per vocabulary type, holding its name, so code that reads
 * facts names a predicate or entity type as {@code TypeNames.CALLS_HTTP} rather than copying the
 * string (ADR 0114). It is committed and checked as the attribute records are ({@link
 * AttributeRecords#check}).
 */
public final class TypeNames {

  private TypeNames() {}

  /**
   * The source of the class.
   *
   * @param vocabulary a vocabulary holding the types
   * @param types the names of the types to name
   * @param packageName the package of the class
   * @param className the simple name of the class
   * @return the source by file name
   * @throws IllegalArgumentException if two types give one constant name
   */
  public static Map<String, String> generate(
      Vocabulary vocabulary, Collection<String> types, String packageName, String className) {
    Map<String, VocabularyType> byConstant = new TreeMap<>();
    for (String name : types) {
      VocabularyType type = vocabulary.find(name).orElseThrow();
      VocabularyType clash = byConstant.put(constantName(name), type);
      if (clash != null && !clash.name().equals(name)) {
        throw new IllegalArgumentException(
            "Types " + clash.name() + " and " + name + " give one constant name");
      }
    }
    StringBuilder out = new StringBuilder();
    out.append("package ").append(packageName).append(";\n\n");
    out.append("/**\n")
        .append(" * The name of every vocabulary type, generated by {@code ")
        .append(TypeNames.class.getName())
        .append("}; do not edit.\n")
        .append(" */\n");
    out.append("public final class ").append(className).append(" {\n\n");
    out.append("  private ").append(className).append("() {}\n");
    for (Map.Entry<String, VocabularyType> entry : byConstant.entrySet()) {
      VocabularyType type = entry.getValue();
      out.append("\n  /** The ")
          .append(type.kind().jsonName())
          .append(" type {@code ")
          .append(type.name())
          .append("}. */\n");
      out.append("  public static final String ")
          .append(entry.getKey())
          .append(" = \"")
          .append(type.name())
          .append("\";\n");
    }
    out.append("}\n");
    return Map.of(className + ".java", out.toString());
  }

  /** The constant's name: the type's name in upper case, with underscores for its separators. */
  static String constantName(String type) {
    return type.replace('-', '_').replace('.', '_').toUpperCase(Locale.ROOT);
  }
}
